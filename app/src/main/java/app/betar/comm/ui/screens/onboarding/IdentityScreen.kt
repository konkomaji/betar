/**
 * Renamed 2026-11-01 from `NicknameScreen.kt` for the pivot's identity system. Shows the real
 * identity reveal (the short ID, a fingerprint of the device's own keypair, permanent and
 * unchangeable) alongside an optional, editable, explicitly non-unique display username. Keys
 * are already generated by the time this screen runs (`MeshApplication.identity` is created
 * lazily on first access and `KeystoreIdentityStore` persists it), so there is nothing to wait
 * on here. [onDone] fires with the username actually in effect, whether the user typed one or
 * left the generated placeholder; [IdentityStore] is the only persistence for the username,
 * there is no account or profile system for this to belong to. The ID itself is never persisted
 * separately since it is always re-derivable from the identity.
 */
@Composable
fun IdentityScreen(onDone: () -> Unit) {
    val context = LocalContext.current
    val app = context.applicationContext as MeshApplication
    val shortId = remember { IdentityStore.shortIdFrom(app.identity.fingerprintHex()) }
    var username by remember { mutableStateOf(IdentityStore.loadOrGenerate(context)) }
    val usernameValid = remember(username) { IdentityStore.isValidUsername(username) }

    Column(Modifier.fillMaxSize().padding(20.dp)) {
        Text("Your ID", style = MaterialTheme.typography.headlineMedium)
        androidx.compose.foundation.layout.Spacer(Modifier.height(12.dp))
        Text(
            "Generated just now from your device's own key. It is permanent on this device, and it is not tied to your name, phone number or email.",
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        androidx.compose.foundation.layout.Spacer(Modifier.height(18.dp))

        Box(
            modifier = Modifier
                .fillMaxWidth()
                .height(76.dp)
                .clip(MaterialTheme.shapes.large)
                .background(MaterialTheme.colorScheme.secondaryContainer),
            contentAlignment = Alignment.Center,
        ) {
            Text(
                shortId,
                style = MaterialTheme.typography.headlineLarge,
                color = MaterialTheme.colorScheme.onSecondaryContainer,
            )
        }
        androidx.compose.foundation.layout.Spacer(Modifier.height(24.dp))

        Text("Display name", style = MaterialTheme.typography.titleMedium)
        androidx.compose.foundation.layout.Spacer(Modifier.height(8.dp))
        Text(
            "Optional. 3 to 8 characters, letters and digits plus . and _. Shown next to your ID, not instead of it. Not guaranteed to be unique to you, since no server exists to check that.",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        androidx.compose.foundation.layout.Spacer(Modifier.height(10.dp))

        Box(
            modifier = Modifier
                .fillMaxWidth()
                .height(56.dp)
                .clip(MaterialTheme.shapes.large)
                .background(MaterialTheme.colorScheme.surface)
                .border(
                    2.dp,
                    if (usernameValid) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.error,
                    MaterialTheme.shapes.large,
                )
                .padding(horizontal = 20.dp),
            contentAlignment = Alignment.CenterStart,
        ) {
            BasicTextField(
                value = username,
                onValueChange = { if (it.length <= 8) username = it },
                textStyle = MaterialTheme.typography.titleLarge.copy(color = MaterialTheme.colorScheme.onSurface),
                singleLine = true,
            )
        }
        androidx.compose.foundation.layout.Spacer(Modifier.height(14.dp))

        Row(verticalAlignment = Alignment.CenterVertically) {
            Box(Modifier.size(22.dp).clip(BetarPolygonShapes.cookie9).background(MaterialTheme.colorScheme.tertiary))
            androidx.compose.foundation.layout.Spacer(Modifier.size(10.dp))
            Text(
                "Picked for you, change it if you like",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
        androidx.compose.foundation.layout.Spacer(Modifier.height(16.dp))

        Box(
            modifier = Modifier
                .fillMaxWidth()
                .clip(MaterialTheme.shapes.medium)
                .background(MaterialTheme.colorScheme.secondaryContainer)
                .padding(18.dp),
        ) {
            Text(
                "No phone number, no email, nothing to hand over. Panic wipe or reinstalling this app both retire this ID for good and start over with a new one.",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSecondaryContainer,
            )
        }

        androidx.compose.foundation.layout.Spacer(Modifier.weight(1f))

        Button(
            onClick = {
                if (usernameValid) {
                    IdentityStore.save(context, username)
                    onDone()
                }
            },
            enabled = usernameValid,
            modifier = Modifier.fillMaxWidth().height(56.dp),
        ) { Text("Get started") }

        OutlinedButton(
            onClick = {
                IdentityStore.save(context, "")
                onDone()
            },
            modifier = Modifier.fillMaxWidth().height(56.dp).padding(top = 8.dp),
        ) { Text("Skip, use the picked name") }
    }
}
